<?php

// Compile physical geometry into external CSS/SVG, compatible with Foodie's
// production CSP (style-src 'self'; no unsafe-inline or browser exceptions).
$root = dirname(__DIR__);
$geometry = require $root.'/config/archive.php';
[$width, $height] = $geometry['canvas'];
$selectors = [
    'marquee' => '.memory-machine__marquee',
    'slots' => '.memory-slots',
    'screen' => '.memory-machine__screen',
    'indicators' => '.memory-machine__display',
    'tray' => '.memory-tray',
    'lip' => '.memory-tray__lip',
    'upper' => '[data-memory-another]',
    'lower' => '[data-memory-reset]',
];
$css = "/* Generated by tools/build-archive-geometry.php from config/archive.php. */\n";
foreach ($geometry['bounds'] as $name => [$x, $y, $w, $h]) {
    $css .= $selectors[$name].sprintf(" { --x: %.5f%%; --y: %.5f%%; --w: %.5f%%; --h: %.5f%%; }\n", $x / $width * 100, $y / $height * 100, $w / $width * 100, $h / $height * 100);
}
file_put_contents($root.'/resources/css/archive-geometry.css', $css);
foreach ($geometry['slot_bounds'] as $index => [$x, $y, $w, $h]) {
    $css .= '.memory-slot:nth-child('.($index + 1).')'.sprintf(" { --sx: %.5f%%; --sy: %.5f%%; --sw: %.5f%%; --sh: %.5f%%; }\n", $x / 800 * 100, $y / 565 * 100, $w / 800 * 100, $h / 565 * 100);
}
file_put_contents($root.'/resources/css/archive-geometry.css', $css);
